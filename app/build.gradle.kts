// 可选的正式签名：仓库根目录放 keystore.properties（不要提交），内容：
//   storeFile=/absolute/or/relative/path/release.jks
//   storePassword=...
//   keyAlias=...
//   keyPassword=...
// 没有这个文件时 release 回退到 debug 签名，方便本地覆盖安装、保留数据。
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
