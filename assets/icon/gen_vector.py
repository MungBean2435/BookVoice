"""Emit the adaptive-icon vector drawables from the same 108x108 geometry
used by render_icon.py. Run from the repo root:

    python3 assets/icon/gen_vector.py
"""
import math

PAPER = "#F5EBD8"
FOLD = "#CDBA9A"
CREASE = "#B09C7C"
ACCENT = "#E9A43E"
SCALE = 0.84  # keep the mark inside the 66dp adaptive-icon safe circle
SHIFT = round((108 - 108 * SCALE) / 2, 2)

PAGE = (
    "M38,24 H64 L80,40 V74 A10,10 0 0 1 70,84 H38 "
    "A10,10 0 0 1 28,74 V34 A10,10 0 0 1 38,24 Z"
)
FOLD_PATH = "M64,24 L80,40 L64,40 Z"
CREASE_PATH = "M64,24 L80,40"


def wave_path():
    x0, x1, cy, amp, cycles = 34.0, 74.0, 53.0, 10.5, 3.4
    pts = []
    x = x0
    while x <= x1 + 1e-9:
        t = (x - x0) / (x1 - x0)
        env = math.sin(math.pi * t) ** 0.55
        y = cy - amp * env * math.sin(t * cycles * 2 * math.pi)
        pts.append((x, y))
        x += 0.4
    head = "M{:.1f},{:.1f}".format(*pts[0])
    return head + " " + " ".join("L{:.1f},{:.1f}".format(*p) for p in pts[1:])


FOREGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/icon/gen_vector.py - keep in sync with render_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{scale}"
        android:scaleY="{scale}"
        android:translateX="{shift}"
        android:translateY="{shift}">
        <path
            android:fillColor="{paper}"
            android:pathData="{page}" />
        <path
            android:fillColor="{fold}"
            android:pathData="{fold_path}" />
        <path
            android:strokeColor="{crease}"
            android:strokeWidth="0.9"
            android:pathData="{crease_path}" />
        <path
            android:fillColor="#00000000"
            android:strokeColor="{accent}"
            android:strokeWidth="5.2"
            android:strokeLineCap="round"
            android:strokeLineJoin="round"
            android:pathData="{wave}" />
    </group>
</vector>
""".format(scale=SCALE, shift=SHIFT, paper=PAPER, fold=FOLD, crease=CREASE,
           accent=ACCENT, page=PAGE, fold_path=FOLD_PATH, crease_path=CREASE_PATH,
           wave=wave_path())

BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="54"
                android:startY="0"
                android:endX="54"
                android:endY="108"
                android:startColor="#1C2E4C"
                android:endColor="#09101C" />
        </aapt:attr>
    </path>
</vector>
"""

ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", path)


if __name__ == "__main__":
    res = "app/src/main/res"
    write(res + "/drawable/ic_launcher_foreground.xml", FOREGROUND)
    write(res + "/drawable/ic_launcher_background.xml", BACKGROUND)
    write(res + "/mipmap-anydpi-v26/ic_launcher.xml", ADAPTIVE)
    write(res + "/mipmap-anydpi-v26/ic_launcher_round.xml", ADAPTIVE)
